/* =========================================================
   GET GIRL BY ID
========================================================= */

/*
    Example:

    getGirl("001")

    returns the complete database entry
    for Girl 001.
*/

function getGirl(id) {

    const girlID =
        String(id).padStart(3, "0");

    return girls[girlID] || null;

}


/* =========================================================
   GET GIRLS BY GROUP
========================================================= */

/*
    Example:

    getGirlsByGroup(7)

    returns all girls assigned to Group 7.
*/

function getGirlsByGroup(groupNumber) {

    return Object.values(girls).filter(
        girl =>
            girl.group === Number(groupNumber)
    );

}


/* =========================================================
   GET GROUP VOTE LINK
========================================================= */

/*
    Example:

    getGroupVoteLink(7)

    returns the voting form assigned
    to Group 7.
*/

function getGroupVoteLink(groupNumber) {

    return groupVoteLinks[
        Number(groupNumber)
    ] || "#";

}


/* =========================================================
   GET GIRL ASSET PATH
========================================================= */

/*
    Example:

    getGirlAssetPath("001", "A.png")

    returns:

    Wait For It/001/001 A.png
*/

function getGirlAssetPath(id, filename) {

    const girl =
        getGirl(id);


    if (!girl) {
        return "";
    }


    const girlID =
        String(id).padStart(3, "0");


    return (
        `${girl.from}/${girlID}/${girlID} ${filename}`
    );

}


